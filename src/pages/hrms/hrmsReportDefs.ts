const SHORT: ReportPreset[] = ['today', '7d', '30d', 'custom'];

const payroll = (id: PayrollReport, title: string, description: string, extra: Partial<ReportDef> = {}): ReportDef => ({
  id,
  group: 'Payroll',
  title,
  description,
  filter: 'month',
  sheets: true,
  note: 'Needs a calculated payroll run for the month.',
  fetch: (t, q) => fetchReportTables(t, `/hrms/exports/payroll/${q.month}/${id}.xlsx`),
  excel: (t, q) => exportPayrollReportXlsx(t, q.month, id),
  ...extra,
});

